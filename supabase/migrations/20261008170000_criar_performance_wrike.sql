create or replace function _performance_wrike.consultar_performance(
  p_inicio date,
  p_fim date,
  p_id_squad bigint default null,
  p_id_pessoa bigint default null
)
returns jsonb
language sql
stable
security invoker
set search_path = _performance_wrike, pg_temp
as $$
with itens_filtrados as (
  select i.*
  from itens_trabalho i
  where (p_id_squad is null or i.id_squad = p_id_squad)
    and (p_id_pessoa is null or exists (
      select 1 from responsaveis_itens ri
      where ri.id_item_trabalho = i.id and ri.id_pessoa = p_id_pessoa and ri.ativo
    ))
), ciclos as (
  select h.id_item_trabalho,
    min(h.ocorrido_em) filter (where m.considera_execucao and h.origem = 'webhook') as inicio_execucao,
    min(h.ocorrido_em) filter (where m.encerra_ciclo and h.origem = 'webhook') as fim_execucao
  from historico_status_itens h
  left join mapeamentos_status m on m.id_status_wrike = h.id_status_novo
  group by h.id_item_trabalho
), itens_com_ciclo as (
  select i.*, extract(epoch from (c.fim_execucao - c.inicio_execucao)) / 86400.0 as dias_ciclo
  from itens_filtrados i
  left join ciclos c on c.id_item_trabalho = i.id and c.fim_execucao >= c.inicio_execucao
), auditoria as (
  select i.id, i.id_wrike, i.titulo, i.link_wrike,
    coalesce(string_agg(p.problema, '; ' order by p.problema), '') as problemas
  from itens_filtrados i
  cross join lateral (values
    (case when not i.descricao_preenchida then 'Sem descrição' end),
    (case when i.prazo_em is null then 'Sem prazo' end),
    (case when i.okr is null or btrim(i.okr) = '' or lower(i.okr) = 'nenhum' then 'OKR ausente ou Nenhum' end),
    (case when jsonb_array_length(i.itens) = 0 then 'Itens ausente' end),
    (case when i.itens ? 'Outro' then 'Itens contém Outro' end),
    (case when not exists (select 1 from responsaveis_itens ri where ri.id_item_trabalho = i.id and ri.ativo) then 'Sem responsável' end)
  ) p(problema)
  where p.problema is not null
  group by i.id, i.id_wrike, i.titulo, i.link_wrike
), intervalos_status as (
  select h.id_item_trabalho,
    coalesce(m.nome_status, h.nome_status_novo, 'Não classificado') as etapa,
    extract(epoch from (lead(h.ocorrido_em) over (partition by h.id_item_trabalho order by h.ocorrido_em) - h.ocorrido_em)) / 86400.0 as dias
  from historico_status_itens h
  join itens_filtrados i on i.id = h.id_item_trabalho
  left join mapeamentos_status m on m.id_status_wrike = h.id_status_novo
), gargalos as (
  select etapa, round(avg(dias)::numeric, 1) as dias_medios
  from intervalos_status
  where dias is not null and dias >= 0
  group by etapa
), metricas as (
  select count(*) as total,
    count(*) filter (where grupo_status in ('Active', 'Deferred')) as em_andamento,
    count(*) filter (where concluido_em::date between p_inicio and p_fim) as entregues,
    count(*) filter (where grupo_status = 'Cancelled' and atualizado_no_wrike_em::date between p_inicio and p_fim) as cancelados,
    count(*) filter (where okr is not null and btrim(okr) <> '' and lower(okr) <> 'nenhum') as com_okr,
    (select count(*) from auditoria) as itens_com_problema
  from itens_filtrados
)
select jsonb_build_object(
  'periodo', jsonb_build_object('inicio', p_inicio, 'fim', p_fim),
  'metricas', (select to_jsonb(metricas) from metricas),
  'status', coalesce((select jsonb_agg(jsonb_build_object('nome', nome_status, 'quantidade', quantidade) order by quantidade desc)
    from (select nome_status, count(*) as quantidade from itens_filtrados group by nome_status) x), '[]'::jsonb),
  'squads', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'nome', s.nome, 'tipo_grupo', s.tipo_grupo, 'em_andamento', coalesce(x.em_andamento, 0), 'entregues', coalesce(x.entregues, 0), 'cobertura_okr', coalesce(x.cobertura_okr, 0)) order by s.tipo_grupo, s.nome)
    from squads s left join (
      select id_squad, count(*) filter (where grupo_status in ('Active', 'Deferred')) as em_andamento,
        count(*) filter (where concluido_em::date between p_inicio and p_fim) as entregues,
        round(100.0 * count(*) filter (where okr is not null and btrim(okr) <> '' and lower(okr) <> 'nenhum') / nullif(count(*), 0), 1) as cobertura_okr
      from itens_filtrados group by id_squad
    ) x on x.id_squad = s.id where s.ativo), '[]'::jsonb),
  'pessoas', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'nome', p.nome, 'em_andamento', coalesce(x.em_andamento, 0), 'entregues', coalesce(x.entregues, 0), 'dias_ciclo_medio', x.dias_ciclo_medio) order by coalesce(x.em_andamento, 0) desc, p.nome)
    from pessoas p left join (
      select ri.id_pessoa, count(*) filter (where i.grupo_status in ('Active', 'Deferred')) as em_andamento,
        count(*) filter (where i.concluido_em::date between p_inicio and p_fim) as entregues,
        round(avg(ic.dias_ciclo)::numeric, 1) as dias_ciclo_medio
      from responsaveis_itens ri join itens_filtrados i on i.id = ri.id_item_trabalho
      left join itens_com_ciclo ic on ic.id = i.id where ri.ativo group by ri.id_pessoa
    ) x on x.id_pessoa = p.id where p.ativo), '[]'::jsonb),
  'top_itens', coalesce((select jsonb_agg(jsonb_build_object('titulo', titulo, 'link_wrike', link_wrike, 'nome_status', nome_status, 'dias_ciclo', dias_ciclo, 'squad', squad) order by dias_ciclo desc)
    from (select ic.titulo, ic.link_wrike, ic.nome_status, round(ic.dias_ciclo::numeric, 1) as dias_ciclo, s.nome as squad from itens_com_ciclo ic left join squads s on s.id = ic.id_squad where ic.dias_ciclo is not null order by ic.dias_ciclo desc limit 10) t), '[]'::jsonb),
  'gargalos', coalesce((select jsonb_agg(jsonb_build_object('etapa', etapa, 'dias_medios', dias_medios) order by dias_medios desc) from gargalos), '[]'::jsonb),
  'auditoria', coalesce((select jsonb_agg(jsonb_build_object('id_wrike', id_wrike, 'titulo', titulo, 'link_wrike', link_wrike, 'problemas', problemas) order by titulo) from (select * from auditoria order by titulo limit 50) a), '[]'::jsonb),
  'avisos', jsonb_build_array('Bugs críticos e validação de hipóteses dependem de campos de classificação ainda não cadastrados.', 'Cycle time considera apenas transições registradas após a ativação do webhook.')
);
$$;

