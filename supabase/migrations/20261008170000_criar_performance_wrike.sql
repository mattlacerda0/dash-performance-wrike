create schema if not exists _performance_wrike;

revoke all on schema _performance_wrike from public, anon, authenticated;
grant usage on schema _performance_wrike to service_role;

create table if not exists _performance_wrike.squads (
  id bigint generated by default as identity primary key,
  id_wrike text not null unique,
  nome text not null,
  tipo_grupo text not null check (tipo_grupo in ('squad', 'area')),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists _performance_wrike.pessoas (
  id bigint generated by default as identity primary key,
  id_wrike text not null unique,
  nome text not null,
  email text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists _performance_wrike.itens_trabalho (
  id bigint generated by default as identity primary key,
  id_wrike text not null unique,
  titulo text not null,
  link_wrike text,
  id_squad bigint references _performance_wrike.squads(id) on delete set null,
  nome_status text not null,
  grupo_status text not null,
  id_status_wrike text,
  itens jsonb not null default '[]'::jsonb,
  okr text,
  criado_no_wrike_em timestamptz,
  inicio_planejado_em timestamptz,
  prazo_em timestamptz,
  concluido_em timestamptz,
  atualizado_no_wrike_em timestamptz,
  descricao_preenchida boolean not null default false,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table if not exists _performance_wrike.responsaveis_itens (
  id_item_trabalho bigint not null references _performance_wrike.itens_trabalho(id) on delete cascade,
  id_pessoa bigint not null references _performance_wrike.pessoas(id) on delete cascade,
  associado_em timestamptz not null default now(),
  ativo boolean not null default true,
  primary key (id_item_trabalho, id_pessoa)
);

create table if not exists _performance_wrike.mapeamentos_status (
  id_status_wrike text primary key,
  nome_status text not null,
  etapa_analitica text not null check (etapa_analitica in ('planejamento', 'execucao', 'concluido', 'nao_classificado')),
  considera_execucao boolean not null default false,
  encerra_ciclo boolean not null default false,
  ativo boolean not null default true,
  atualizado_em timestamptz not null default now()
);

create table if not exists _performance_wrike.historico_status_itens (
  id bigint generated by default as identity primary key,
  id_item_trabalho bigint not null references _performance_wrike.itens_trabalho(id) on delete cascade,
  id_status_anterior text,
  nome_status_anterior text,
  id_status_novo text,
  nome_status_novo text,
  ocorrido_em timestamptz not null,
  recebido_em timestamptz not null default now(),
  origem text not null check (origem in ('webhook', 'reconciliacao'))
);

create table if not exists _performance_wrike.eventos_wrike (
  id bigint generated by default as identity primary key,
  chave_idempotencia text not null unique,
  tipo_evento text not null,
  corpo jsonb not null,
  recebido_em timestamptz not null default now(),
  processado_em timestamptz,
  erro_processamento text
);

create table if not exists _performance_wrike.sincronizacoes_wrike (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('inicial', 'reconciliacao', 'webhook')),
  iniciado_em timestamptz not null default now(),
  finalizado_em timestamptz,
  itens_lidos integer not null default 0,
  itens_atualizados integer not null default 0,
  resultado text not null default 'em_andamento' check (resultado in ('em_andamento', 'sucesso', 'erro')),
  detalhe_erro text
);

create index if not exists itens_trabalho_squad_status_idx on _performance_wrike.itens_trabalho (id_squad, grupo_status);
create index if not exists itens_trabalho_concluido_idx on _performance_wrike.itens_trabalho (concluido_em desc) where concluido_em is not null;
create index if not exists itens_trabalho_ativos_idx on _performance_wrike.itens_trabalho (id_squad, atualizado_no_wrike_em desc) where grupo_status in ('Active', 'Deferred');
create index if not exists responsaveis_itens_pessoa_idx on _performance_wrike.responsaveis_itens (id_pessoa, id_item_trabalho) where ativo;
create index if not exists historico_status_item_ocorrido_idx on _performance_wrike.historico_status_itens (id_item_trabalho, ocorrido_em);
create index if not exists historico_status_ocorrido_idx on _performance_wrike.historico_status_itens (ocorrido_em desc);
create index if not exists eventos_wrike_recebido_idx on _performance_wrike.eventos_wrike (recebido_em desc);

create or replace function _performance_wrike.definir_atualizado_em()
returns trigger
language plpgsql
set search_path = _performance_wrike, pg_temp
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists squads_atualizado_em on _performance_wrike.squads;
create trigger squads_atualizado_em before update on _performance_wrike.squads for each row execute function _performance_wrike.definir_atualizado_em();
drop trigger if exists pessoas_atualizado_em on _performance_wrike.pessoas;
create trigger pessoas_atualizado_em before update on _performance_wrike.pessoas for each row execute function _performance_wrike.definir_atualizado_em();
drop trigger if exists itens_trabalho_atualizado_em on _performance_wrike.itens_trabalho;
create trigger itens_trabalho_atualizado_em before update on _performance_wrike.itens_trabalho for each row execute function _performance_wrike.definir_atualizado_em();

